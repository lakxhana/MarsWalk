import assert from 'node:assert/strict';
import {DEFAULT_OPERATIONS,startStop,finishStop,stopSeconds,stopLevel,oxygenRemaining,operationsReport,recordEvidence} from '../src/lib/crewOperations';
import {readingState,validateReading,healthWarnings} from '../src/lib/healthMonitoring';
import {getDeliveredUplinkMessages} from '../src/lib/earthMonitoring';
import type {ObservationRecord,CommMessage} from '../src/lib/storage';
let s={...DEFAULT_OPERATIONS,missionStart:100};
s=startStop(s,120);assert.equal(s.stops.length,1);
assert.equal(startStop(s,180),s,'reopening does not reset stop');
assert.equal(stopSeconds(s.stops[0],180),60);
assert.equal(stopSeconds(s.stops[0],180),60,'paused clock leaves stop unchanged');
assert.equal(stopLevel(s.stops[0],359),'normal');assert.equal(stopLevel(s.stops[0],360),'soon');assert.equal(stopLevel(s.stops[0],420),'exceeded');
assert.equal(oxygenRemaining(s,220),118,'oxygen includes stops');
s=finishStop(s,450);assert.equal(stopSeconds(s.stops[0],900),330,'completed stop frozen');
s=startStop(s,500);assert.equal(s.stops.length,2);assert.equal(s.stops[1].started,500);
assert.deepEqual(JSON.parse(JSON.stringify(s)),s,'SQLite JSON roundtrip preserves stop history');
const obs={id:'evidence',createdAtSimTime:510,note:'Fine layers visible',imageRef:'data:image/jpeg;base64,a',imageIsArchival:false} as ObservationRecord;
assert.equal(recordEvidence(s,obs,false).taskPhoto,false,'en-route evidence does not complete destination task');
s=recordEvidence(s,obs,true);assert.equal(s.taskPhoto,true);assert.equal(s.taskNote,true);
assert.equal(recordEvidence(s,obs,true).observationIds.length,1,'evidence idempotent');
const report=operationsReport(s,520);const packet={id:'r',direction:'uplink',sentAtSimTime:520,deliveredAtSimTime:820,statusSnapshot:{operations:report}} as CommMessage;
assert.equal(getDeliveredUplinkMessages([packet],819).length,0,'no Earth leak');
assert.equal(getDeliveredUplinkMessages([packet],820)[0].statusSnapshot?.operations?.stop?.elapsedSeconds,20,'Earth uses captured stop age');
assert.equal(report.stop?.elapsedSeconds,20,'Earth report does not advance with current clock');
assert.equal(readingState(undefined,0),'missing');
const r={metric:'heartRate' as const,value:130,capturedAt:500,source:'manual' as const,low:null,high:120};
assert.equal(readingState(r,520),'high');assert.equal(readingState(r,561),'stale');
assert.equal(validateReading('heartRate',NaN,null,null),false);assert.equal(validateReading('heartRate',80,100,50),false);assert.equal(validateReading('heartRate',80,null,null),true);
assert.equal(healthWarnings({heartRate:r},520).length,1);assert.equal(healthWarnings({heartRate:r},561).length,0,'old data not evaluated as current');
const done={...finishStop(s,530),completedAt:530};assert.equal(oxygenRemaining(done,900),oxygenRemaining(done,530),'tank estimate frozen after mission');
console.log('Crew operations: 26 checks passed');

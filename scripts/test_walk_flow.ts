import { strict as assert } from 'node:assert';
import {initialWalkMode,hasReachedDestination,resumeWalkMode,reportedMovement} from '../src/lib/walkFlow';
assert.equal(initialWalkMode(true,false),'following');
assert.equal(initialWalkMode(false,false),'paused');
assert.equal(initialWalkMode(true,true),'paused');
assert.equal(initialWalkMode(true,false,'investigating'),'paused');
assert.equal(initialWalkMode(true,false,'following'),'following');
assert.equal(initialWalkMode(true,false,'clickToWalk'),'paused');
assert.equal(resumeWalkMode(false),'following');
assert.equal(resumeWalkMode(true),'paused');
assert.equal(hasReachedDestination(80,1),false);
assert.equal(hasReachedDestination(0,10),false);
assert.equal(hasReachedDestination(0.5,0.5),true);
assert.equal(reportedMovement('paused',false,false,true,false),'Stopped');
assert.equal(reportedMovement('investigating',false,false,false,false),'Investigating');
assert.equal(reportedMovement('investigating',false,true,false,false),'Recording');
assert.equal(reportedMovement('following',true,false,false,false),'Stopped');
assert.equal(reportedMovement('following',false,false,false,false),'Walking');
assert.equal(reportedMovement('following',false,false,true,false),'Returning');
assert.equal(reportedMovement('manual',false,false,false,false),'Stopped');
console.log('PASS 18 walk lifecycle checks: automatic start, investigate/resume, endpoint protection and Earth activity states');

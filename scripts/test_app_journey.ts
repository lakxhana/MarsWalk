import assert from 'node:assert/strict';
import {createElement} from 'react';
import {act,create,type ReactTestRenderer} from 'react-test-renderer';
import App from '../src/App';
import Header from '../src/components/Header';
import NamedSitePlanner from '../src/components/NamedSitePlanner';
import MissionReview from '../src/components/MissionReview';
import FieldWalk from '../src/components/FieldWalk';
import EarthTeamMonitoring from '../src/components/EarthTeamMonitoring';
import RegionalMap from '../src/components/RegionalMap';
import {namedRoute} from '../src/lib/jezeroRoutes';
import type {CommMessage} from '../src/lib/storage';
const data=new Map<string,string>();
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>data.set(k,v)}});
const timers=new Map<number,()=>void>();let timerId=0;
Object.assign(globalThis,{setInterval:(fn:()=>void)=>{timers.set(++timerId,fn);return timerId;},clearInterval:(id:number)=>timers.delete(id)});
const packets=new Map<string,CommMessage>();
Object.assign(globalThis,{fetch:async(url:string,options:{method?:string;body?:string}={})=>{if(url.endsWith('/messages')&&options.method==='PUT'){const m=JSON.parse(options.body!);packets.set(m.id,m);}return {ok:true,json:async()=>url.endsWith('/messages')?[...packets.values()]:url.endsWith('/tasks')||url.endsWith('/observations')?[]:{}};}});
const tick=async()=>{await act(async()=>{for(const fn of [...timers.values()])fn();});};
async function run(){
 let ui:ReactTestRenderer;await act(async()=>{ui=create(createElement(App,{initialMission:null}));});
 const header=()=>ui.root.findByType(Header);
 await act(async()=>header().props.onChangeRole('science_team'));assert.equal(header().props.currentView,'globe');
 await act(async()=>header().props.onNavigate('plan'));
 const planner=()=>ui.root.findByType(NamedSitePlanner);
 const task={id:'earth-job',title:'Earth assigned rock photo',minutes:5,priority:5,fraction:.5,done:false};
 await act(async()=>planner().props.onCrew({...planner().props.crew,name:'Rae',tankId:'Tank A',routeTasks:[task],plannedStops:1}));
 await act(async()=>planner().props.onStart(namedRoute('skinner-ridge','wildcat-ridge')));
 assert.equal(ui.root.findAllByType(FieldWalk).length,0,'sending does not start walking');
 assert.equal(planner().props.readOnly,true,'the sent planner remains visible');
 assert.equal(planner().props.lockedRoute.destinationName,'Wildcat Ridge');
 assert.equal(planner().props.crew.routeTasks[0].title,task.title,'sent tasks remain visible');
 const crewShortcut=ui.root.findAllByType('button').find(b=>b.children.join('')==='Open Mars crew');assert.ok(crewShortcut,'sent planner provides a review/start shortcut');
 await act(async()=>crewShortcut!.props.onClick());assert.equal(header().props.currentView,'plan');
 assert.equal(header().props.missionReady,true);
 const startButton=ui.root.findByProps({className:'review-actions'}).findAllByType('button').find(b=>b.children.join('')==='Start walk →');
 assert.ok(startButton&&startButton.props.disabled,'Start walk stays visible and gated in the review footer');
 for(const input of ui.root.findByProps({'aria-label':'Pre-walk checklist'}).findAllByType('input'))await act(async()=>input.props.onChange({target:{checked:true}}));
 assert.equal(startButton!.props.disabled,false,'all review acknowledgements unlock Start');
 await act(async()=>header().props.onChangeRole('explorer'));assert.equal(header().props.currentView,'plan');
 assert.equal(ui.root.findByType(MissionReview).props.proposal.crew.routeTasks[0].title,task.title);
 assert.equal(ui.root.findAllByType(FieldWalk).length,0);
 await act(async()=>startButton!.props.onClick());assert.equal(ui.root.findByType(FieldWalk).props.crew.routeTasks[0].title,task.title);
 await tick();await act(async()=>header().props.onChangeRole('science_team'));assert.equal(header().props.currentView,'science');
 const pos=ui.root.findByType(EarthTeamMonitoring).findByType(RegionalMap).props.position;assert.ok(pos);
 await tick();const moved=ui.root.findByType(EarthTeamMonitoring).findByType(RegionalMap).props.position;assert.ok(moved.x!==pos.x||moved.z!==pos.z,'Earth marker moves while Earth workspace open');
 const saved=JSON.parse(data.get('marswalk_mission_state_v1')!);
 await act(async()=>ui.unmount());
 await act(async()=>{ui=create(createElement(App,{initialMission:saved}));});
 assert.equal(ui.root.findAllByType(FieldWalk).length,0,'saved walk does not mount or progress');
 const frozen=header().props.simTime;await tick();assert.equal(header().props.simTime,frozen,'saved clock remains frozen');
 await act(async()=>header().props.onChangeRole('explorer'));assert.equal(header().props.currentView,'plan');assert.equal(ui.root.findByType(MissionReview).props.savedWalk,true);
 await act(async()=>ui.root.findByType(MissionReview).props.onResumeSaved());assert.equal(ui.root.findAllByType(FieldWalk).length,1);await tick();assert.ok(header().props.simTime>frozen);
 await act(async()=>ui.unmount());
 const orphan={...saved,missionStartedAtSimTime:null,crewOperations:{...saved.crewOperations,missionStart:null},missionProposal:{...saved.missionProposal,status:'accepted'}};
 await act(async()=>{ui=create(createElement(App,{initialMission:orphan}));});
 await act(async()=>header().props.onChangeRole('explorer'));assert.equal(ui.root.findAllByType(FieldWalk).length,0,'an old accepted proposal alone must not start walking');
 assert.ok(ui.root.findAllByType('button').some(b=>b.children.join('')==='Open Earth planning'));
 await act(async()=>header().props.onChangeRole('science_team'));await act(async()=>header().props.onNavigate('plan'));
 assert.equal(planner().props.readOnly,false,'orphaned accepted plans do not permanently lock the planner');
 await act(async()=>ui.unmount());console.log('PASS full App: visible sent planner, Mars review/start, Earth movement, saved-walk resume and orphan recovery');
}
run().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1);});

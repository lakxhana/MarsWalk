 assert.equal(saved.length,1);assert.equal(saved[0].direction,'downlink');assert.equal(saved[0].deliveredAtSimTime,610);assert.equal(draft().props.value,'');
 await act(async()=>ui.update(createElement(FloatingChat,{...props,messages:[message,...saved],now:609,side:'mars',open:false})));
 assert.equal(launcher().props['aria-label'],'Open chat','own sent message is not incoming');
 await act(async()=>ui.update(createElement(FloatingChat,{...props,messages:[message,...saved],now:610,side:'mars',open:false})));

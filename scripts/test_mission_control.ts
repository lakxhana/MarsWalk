import assert from 'node:assert/strict';
import {createElement} from 'react';
import {act,create} from 'react-test-renderer';
import EarthTeamMonitoring from '../src/components/EarthTeamMonitoring';
import EarthFirstPerson from '../src/components/EarthFirstPerson';
import WalkScene from '../src/components/WalkScene';
import SuitMonitor from '../src/components/SuitMonitor';
import RegionalMap from '../src/components/RegionalMap';
import SurfaceReadout from '../src/components/SurfaceReadout';
import {receivedWalkRoute} from '../src/lib/missionControl';
import {namedRoute} from '../src/lib/jezeroRoutes';
import type {CommMessage,MissionStatusSnapshot} from '../src/lib/storage';
import {DEFAULT_OPERATIONS,operationsReport} from '../src/lib/crewOperations';

async function run(){
 const route=namedRoute('skinner-ridge','wildcat-ridge')!;
 assert.equal(receivedWalkRoute([],'bad'),null);
 assert.equal(receivedWalkRoute([{x:0,z:0},{x:0,z:0}],'bad'),null);
 assert.equal(receivedWalkRoute([{x:NaN,z:0},{x:0,z:0}],'bad'),null);
 assert.deepEqual(receivedWalkRoute([{x:0,z:0},{x:3,z:4},{x:3,z:8}],'ok')?.points.map(p=>p.distanceFromStart),[0,5,9]);
 const snap:MissionStatusSnapshot={missionId:'control',sequenceNumber:1,capturedAtSimTime:10,planVersion:1,position:{...route.points[0]},headingRadians:1,mapMode:'regional',plannedRoutePoints:route.points,coordinateReference:'Jezero crop',missionElapsedSeconds:10,missionBudgetMinutes:60,reserveMinutes:10,returnEstimateMinutes:1,movementState:'Walking',operations:operationsReport({...DEFAULT_OPERATIONS,missionStart:0},10)};
 const packet:CommMessage={id:'report',kind:'status_update',direction:'uplink',questionText:'',observationId:'',siteId:'',siteName:'',taskId:null,originalPlanVersion:1,originalPlanSummary:'',status:'in_transit',sentAtSimTime:10,deliveredAtSimTime:310,statusSnapshot:snap};
 const noop=()=>{};
 const props={messages:[packet],simTime:309,statusUpdateIntervalSeconds:5,oneWayDelayMinutes:5,simulationPaused:false,missionActive:true,simulationSpeedMultiplier:1,missionName:'Control test',missionId:'control',isLocalOnly:true,plannedRoute:route,onChangeRole:noop,onToggleSimulation:noop,onSetOneWayDelayMinutes:noop,onSetSimulationSpeedMultiplier:noop,onAdvanceSimTime:noop,onReloadMessages:async()=>{}};
 let ui!:ReturnType<typeof create>;
 await act(async()=>{ui=create(createElement(EarthTeamMonitoring,props));});
 const button=(text:string)=>ui.root.findAllByType('button').find(b=>b.children.join('')===text)!;
 const focus=()=>ui.root.findAllByType('div').find(d=>String(d.props.className).startsWith('support-split'))!.props.className;
 assert.equal(focus(),'support-split focus-split');
 assert.equal(ui.root.findByType(SuitMonitor).props.status,null);
 await act(async()=>button('Open 3D view').props.onClick());
 assert.equal(focus(),'support-split focus-map');
 assert.equal(ui.root.findByType(EarthFirstPerson).props.status,null,'known Earth plan does not expose a crew position before delivery');
 assert.equal(ui.root.findAllByType(WalkScene).length,0);
 await act(async()=>ui.update(createElement(EarthTeamMonitoring,{...props,simTime:310})));
 const firstRoute=ui.root.findByType(WalkScene).props.route;
 assert.equal(ui.root.findByType(WalkScene).props.pose.x,snap.position.x);
 assert.equal(ui.root.findByType(SurfaceReadout).props.position.x,snap.position.x);
 const next={...snap,sequenceNumber:2,capturedAtSimTime:20,position:{...route.points[1]}};
 const future={...packet,id:'later',sentAtSimTime:20,deliveredAtSimTime:320,statusSnapshot:next};
 await act(async()=>ui.update(createElement(EarthTeamMonitoring,{...props,messages:[packet,future],simTime:319})));
 assert.equal(ui.root.findByType(WalkScene).props.pose.x,snap.position.x,'future received position is hidden');
 await act(async()=>ui.update(createElement(EarthTeamMonitoring,{...props,messages:[packet,future],simTime:320})));
 assert.equal(ui.root.findByType(WalkScene).props.pose.x,next.position.x);
 assert.equal(ui.root.findByType(WalkScene).props.route,firstRoute,'unchanged path preserves scene geometry between reports');
 await act(async()=>button('2D map').props.onClick());assert.equal(ui.root.findAllByType(WalkScene).length,0);
 await act(async()=>button('Split view').props.onClick());assert.equal(focus(),'support-split focus-split');
 assert.equal(ui.root.findAllByProps({id:'message-earth'}).length,0,'chat no longer crowds the sidebar');
 await act(async()=>ui.root.findByProps({'aria-label':'Expand suit monitoring'}).props.onClick());
 assert.equal(focus(),'support-split focus-suit');assert.equal(ui.root.findByType(SuitMonitor).props.compact,false);
 await act(async()=>ui.root.findByProps({'aria-label':'Inspect suit metric'}).props.onChange({target:{value:'respiratoryRate'}}));
 await act(async()=>button('Split view').props.onClick());
 await act(async()=>ui.root.findByProps({'aria-label':'Expand suit monitoring'}).props.onClick());
 assert.equal(ui.root.findByProps({'aria-label':'Inspect suit metric'}).props.value,'respiratoryRate');
 await act(async()=>ui.update(createElement(EarthTeamMonitoring,{...props,simTime:500,missionActive:false})));
 assert.equal(ui.root.findAllByType(SuitMonitor).length,0,'ended mission does not expose stale monitoring');
 assert.equal(ui.root.findAllByType(RegionalMap).length,0);
 assert.match(JSON.stringify(ui.toJSON()),/opens when the crew starts/);
 await act(async()=>ui.unmount());
 let opened=0;
 await act(async()=>{ui=create(createElement(RegionalMap,{points:route.points,onOpen:()=>opened++}));});
 const svg=ui.root.findByType('svg');const currentTarget={setPointerCapture:noop,getBoundingClientRect:()=>({width:500,height:500})};
 const pointer=(x:number)=>({clientX:x,clientY:20,pointerId:1,currentTarget});
 await act(async()=>{svg.props.onPointerDown(pointer(20));svg.props.onPointerUp(pointer(20));});assert.equal(opened,1);
 await act(async()=>{svg.props.onPointerDown(pointer(20));svg.props.onPointerMove(pointer(100));svg.props.onPointerUp(pointer(100));});assert.equal(opened,1,'drag pans without opening POV');
 await act(async()=>{svg.props.onPointerDown(pointer(20));svg.props.onPointerCancel();svg.props.onPointerUp(pointer(20));});assert.equal(opened,1);
 await act(async()=>ui.unmount());
 console.log('PASS mission control: split/focus/back, delayed POV, stable scene route, delivered surface position, preserved metric, lifecycle gate and map tap vs drag');
}
run().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1);});

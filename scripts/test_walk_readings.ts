import assert from 'node:assert/strict';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {walkReadings} from '../src/lib/walkReadings';
import {namedRoute,sampleRoute} from '../src/lib/jezeroRoutes';
import {JEZERO_WEATHER} from '../src/lib/weather';
import WalkReadings from '../src/components/WalkReadings';
import SourcesAndCoverageView from '../src/components/SourcesAndCoverageView';
import type {ObservationRecord} from '../src/lib/storage';
const route=namedRoute('skinner-ridge','wildcat-ridge')!;
const start=sampleRoute(route,0),end=sampleRoute(route,route.totalDistanceMeters);
const observation={id:'obs',location:{x:start.x,z:start.z},createdAtSimTime:10,imageIsArchival:false} as ObservationRecord;
const a=walkReadings(start,true,0,[observation],10),b=walkReadings(end,true,0,[observation],10);
assert.equal(a.nearest.site.name,'Skinner Ridge');assert.equal(b.nearest.site.name,'Wildcat Ridge');
assert.notEqual(a.science?.shortGeology,b.science?.shortGeology,'context follows location rather than using destination everywhere');
assert.ok(a.terrain.elevation!==null&&b.terrain.elevation!==null);
assert.equal(a.nearestRecord,0);assert.ok(b.nearestRecord!>0,'record distance follows position');
assert.equal(walkReadings(start,true,0,[observation],9).recordCount,0,'future records excluded');
assert.equal(a.pressure,`${JEZERO_WEATHER.pressure} Pa`);assert.equal(a.temperature,b.temperature,'archived weather is not fabricated as spatial variation');
const missing=walkReadings({x:999999,z:999999},true,10,[],0);
assert.equal(missing.terrain.elevation,null);assert.equal(missing.hazard,'No terrain coverage');
assert.notEqual(a.hazard,'Safe');
if(a.terrain.slope!>0)assert.equal(walkReadings(start,true,a.terrain.slope!/2,[],0).slopeAlert,true);
const html=renderToStaticMarkup(createElement(WalkReadings,{position:start,regional:true,slopeLimit:0,observations:[observation],now:10}));
for(const label of ['Terrain','Elevation','Geology','History','Observations','Temperature','Pressure','Hazards'])assert.match(html,new RegExp(`<dt>${label}</dt>`));
assert.doesNotMatch(html,/<details|<dialog/);assert.match(html,/archived sol 1133/);
const coverage=renderToStaticMarkup(createElement(SourcesAndCoverageView,{}));
assert.match(coverage,/<ul class="coverage-list">/);assert.doesNotMatch(coverage,/bg-amber|text-rose|bg-neutral-50/);
for(const label of ['Temperature &amp; pressure','Health &amp; suit','Legacy east crop','Observations'])assert.ok(coverage.includes(label));
console.log('PASS walk HUD: location-aware science, source weather/pressure, unknown coverage, visible labels and concise source list');

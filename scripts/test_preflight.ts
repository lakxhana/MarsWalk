import assert from 'node:assert/strict';
import {createElement} from 'react';
import {create,act} from 'react-test-renderer';
import {preflight,BASE_O2_RATE} from '../src/lib/preflight';
import {DEFAULT_OPERATIONS} from '../src/lib/crewOperations';
import {namedRoute} from '../src/lib/jezeroRoutes';
import NamedSitePlanner from '../src/components/NamedSitePlanner';
import Header from '../src/components/Header';
import {renderToStaticMarkup} from 'react-dom/server';
const route={...namedRoute('skinner-ridge','wildcat-ridge')!,totalDistanceMeters:660,assumedSpeedMps:1.1};
const crew={...DEFAULT_OPERATIONS};
const result=preflight(route,crew,60,10);
assert.equal(BASE_O2_RATE,86);assert.equal(result.travel,10);assert.equal(result.observe,15);assert.equal(result.total,45);assert.equal(result.missionOxygen,107.5);assert.deepEqual(result.errors,[]);
assert.ok(preflight(route,{...crew,name:' '},60,10).errors.some(e=>e.includes('name')));
assert.ok(preflight(route,crew,30,10).errors.some(e=>e.includes('duration')));
assert.ok(preflight(route,{...crew,oxygenMinutes:65},60,10).errors.some(e=>e.includes('endurance')));
assert.ok(preflight(route,{...crew,oxygenRateGph:NaN},60,10).errors.length);
assert.equal(preflight(route,{...crew,oxygenLossGph:14},60,10).missionOxygen,125);
const header=renderToStaticMarkup(createElement(Header,{currentView:'globe',role:'explorer',missionActive:false,onNavigate:()=>{},onChangeRole:()=>{},simTime:0,simulationPaused:false,onToggleSimulation:()=>{},oneWayDelayMinutes:0,onSetOneWayDelayMinutes:()=>{},onAdvanceSimTime:()=>{},simulationSpeedMultiplier:1,onSetSimulationSpeedMultiplier:()=>{},statusUpdateIntervalSeconds:1,onSetStatusUpdateIntervalSeconds:()=>{}}));
assert.doesNotMatch(header,/>Walk</);assert.doesNotMatch(header,/Return to active walk/);
let starts=0;const ui=create(createElement(NamedSitePlanner,{onStart:()=>starts++,crew}));
assert.equal(ui.root.findAllByType('form')[0].findAllByType('form').length,1,'health entry is not nested in required preflight form');
const details=ui.root.findAllByType('details');const crewSection=details.find(d=>d.findAllByType('summary')[0]?.children.join('')==='Crew & stops')!;
assert.equal(crewSection.findAllByType('details').length,1,'crew section contains no nested task or health panels');
assert.ok(details.some(d=>d.findAllByType('summary')[0]?.children.join('')==='Route tasks'));
act(()=>ui.root.findAllByType('form')[0].props.onSubmit({preventDefault(){}}));assert.equal(starts,1);
act(()=>ui.update(createElement(NamedSitePlanner,{onStart:()=>starts++,crew:{...crew,name:''}})));
act(()=>ui.root.findAllByType('form')[0].props.onSubmit({preventDefault(){}}));assert.equal(starts,1,'invalid crew cannot start');
act(()=>ui.unmount());console.log('PASS preflight arithmetic, shortages, independent sections and explicit start gating');process.exit(0);
